#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""writer：写稿（对应 SOP v8 §05）。

桩模式输出的是一份**能过流水线门禁的最小骨架**：
章节 01/02 编号、判断句标题、作者判断单独标注、无【】占位符、无高危禁用词。
接真实模型后，把 task="writer.draft" 换成真正的提示词即可，门禁不变。
"""
from __future__ import annotations

from datetime import date

from .base import Agent, Context, Result, gather_context, guest_of

SKELETON = """# 待定标题：把主线压成一句可复述的判断

## 导语

这段访谈最值得注意的不是结论，而是结论成立的条件。**作者判断已单独标注，与受访者原话分开。**

本文回答一个问题：当变化已经发生，普通读者的选择会怎样被改变。

## 01｜先被重新定价的是入门岗位

（这一节只推进一个问题：变化最先落在谁身上。）

> 可定位的原话放在这里。
> —— 受访者，原视频 00:00:00 [1]

**这一句是本节结论。**

## 02｜能力在飙升，价格还没动

（解释能力曲线与经济影响之间的裂缝。）

**裂缝来自采用速度，不是模型能力。**

## 03｜什么在涨价：意图、判断、品味

（这一节回答：如果按任务定价，哪些任务变贵了。）

> 第二处原话。
> —— 受访者，原视频 00:00:00 [1]

**变贵的是那些需要人来决定要做什么的任务。**

## 结尾

回到开头的问题：变化已经发生，但兑现方式取决于谁先改变工作方式。

> 本文归纳：三节合起来说明的是一件事——重新定价发生在任务层，不在岗位层。

---

## 来源与说明

[1] 节目名称，发布日期，链接；引文对应原视频时间戳。
"""


class Writer(Agent):
    name = "writer"
    stage = "researched"

    def run(self, ctx: Context) -> Result:
        md = ctx.case_dir / f"{guest_of(ctx.case_dir)}_人味版.md"
        llm = ctx.provider.complete(
            task="writer.draft",
            system=(
                "你是深度报道作者，为一篇人物访谈报道写正文。遵守以下硬性要求：\n"
                "1. 章节写成「## 01｜标题」，标题是判断句，不是「背景/现状/挑战/建议」这类话题词。\n"
                "2. 作者判断必须出现，并用「本文归纳」或「作者判断」标明；不要把判断写成受访者原话。\n"
                "3. 禁止拔高：不写「标志着」「彰显了」「开启了新时代」「让我们拭目以待」。\n"
                "4. 禁止假对比：「不仅……更是」、没有纠正误解的「不是……而是」、「这背后是」式的伪深度。\n"
                "5. 保留不确定性：受访者只是推测的，写「据其自述」「可能」，不写成已证实的事实。\n"
                "6. 引号只用于可定位的原话；改写和拼接不加引号。\n"
                "7. 不用赋能、抓手、闭环、底层逻辑、颗粒度、势能、破局这类词。\n"
                "8. 不用【】占位符，不写「首先/其次/最后」的编号式行文。"
            ),
            prompt=(
                "以下是一篇人物访谈报道的全部素材（选题卡、素材卡、事实台账、研究笔记的节选）。\n"
                "请只使用这些材料写正文；材料里没有的事实、数字、原话一律不要编。\n"
                "如果某处确实缺材料，就写得概括一些，不要标注「待核」之类的占位。\n\n"
                + (gather_context(ctx.case_dir,
                                  ("选题卡", "素材卡", "事实台账", "研究笔记"))
                   or "（素材目录为空）")
                + "\n\n现在写出完整正文。"
            ),
            max_tokens=8000,   # 推理模型含 reasoning，正文需要余量
        )
        ctx.save_llm("writer", llm)

        text = SKELETON if llm.lstrip().startswith("[STUB]") else llm.strip() + "\n"
        self.write(ctx, md, text)
        return Result.ok(f"正文：{md.name}", artifacts={"draft": str(md)}, to="drafted")
